"use client";

import { useCallback, useEffect, useMemo, useState } from "react";
import {
  Download,
  FileCode2,
  Heart,
  History,
  Keyboard,
  PanelLeftClose,
  PanelLeftOpen,
  Command as CommandIcon,
  RotateCcw,
  Search,
  Sparkles,
} from "lucide-react";
import { useGeneration, titleFromPrompt } from "@/lib/use-generation";
import { languageLabel } from "@/lib/parse-stream";
import type { Checkpoint, ProjectFile } from "@/lib/types";
import AssistantPanel from "./AssistantPanel";
import Canvas from "./Canvas";
import CommandPalette, { type Command } from "./CommandPalette";
import FileTree from "./FileTree";
import Logo from "./Logo";
import OnboardingModal from "./OnboardingModal";

const ONBOARDING_KEY = "yanzx-ai:onboarded:v1";
const FAVICON =
  "data:image/svg+xml," +
  encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect width="24" height="24" rx="6" fill="#6366F1"/><path d="M7 6l6 6-6 6M14.5 18H18" stroke="#04060d" stroke-width="2.2" fill="none" stroke-linecap="round" stroke-linejoin="round"/></svg>`
  );

function downloadProject(files: ProjectFile[], prompt: string) {
  const stamp = new Date().toISOString().slice(0, 16).replace(/[:T]/g, "-");
  const header = `# ${titleFromPrompt(prompt)}\n\nGenerated by Yanzx AI. Each section is one project file.\n\n`;
  const body = files
    .map(
      (file) =>
        `## \`${file.path}\`\n\n\`\`\`${file.language === "prisma" ? "prisma" : file.language}\n${file.content}\n\`\`\`\n`
    )
    .join("\n");
  const blob = new Blob([header + body], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `yanzx-${stamp}.md`;
  anchor.click();
  URL.revokeObjectURL(url);
}

export default function Workspace() {
  const {
    files,
    messages,
    checkpoints,
    activeFile,
    isGenerating,
    error,
    notice,
    mode,
    lastPrompt,
    hydrated,
    setActiveFile,
    generate,
    stop,
    restore,
    reset,
    clearError,
  } = useGeneration();

  const [onboardingOpen, setOnboardingOpen] = useState(false);
  const [paletteOpen, setPaletteOpen] = useState(false);
  const [explorerOpen, setExplorerOpen] = useState(true);

  /* Show the onboarding funnel on a first visit only. */
  useEffect(() => {
    if (!hydrated) return;
    try {
      if (localStorage.getItem(ONBOARDING_KEY) !== "1") setOnboardingOpen(true);
    } catch {
      setOnboardingOpen(true);
    }
  }, [hydrated]);

  const dismissOnboarding = useCallback(() => {
    setOnboardingOpen(false);
    try {
      localStorage.setItem(ONBOARDING_KEY, "1");
    } catch {
      /* storage blocked — fine, the modal just reappears next visit */
    }
  }, []);

  const submitFromOnboarding = useCallback(
    (prompt: string) => {
      dismissOnboarding();
      void generate(prompt);
    },
    [dismissOnboarding, generate]
  );

  /* Keyboard shortcuts: ⌘K palette, ⌘/ onboarding, ⌘. stop. */
  useEffect(() => {
    const onKeyDown = (event: KeyboardEvent) => {
      const meta = event.metaKey || event.ctrlKey;
      if (meta && event.key.toLowerCase() === "k") {
        event.preventDefault();
        setPaletteOpen((open) => !open);
      } else if (meta && event.key === "/") {
        event.preventDefault();
        setOnboardingOpen(true);
      } else if (meta && event.key === ".") {
        if (isGenerating) {
          event.preventDefault();
          stop();
        }
      }
    };
    window.addEventListener("keydown", onKeyDown);
    return () => window.removeEventListener("keydown", onKeyDown);
  }, [isGenerating, stop]);

  /* Inline favicon so the tab matches the product without an asset request. */
  useEffect(() => {
    const link = document.querySelector<HTMLLinkElement>("link[rel~='icon']") ?? document.createElement("link");
    link.rel = "icon";
    link.href = FAVICON;
    document.head.append(link);
  }, []);

  const changedPaths = useMemo(() => {
    const latest = checkpoints[0];
    return new Set(latest ? latest.files.map((file) => file.path) : []);
  }, [checkpoints]);

  const totalLines = useMemo(
    () => files.reduce((sum, file) => sum + file.content.split("\n").length, 0),
    [files]
  );

  const commands = useMemo<Command[]>(() => {
    const fileCommands: Command[] = files.map((file) => ({
      id: `file:${file.path}`,
      label: file.path,
      hint: `${languageLabel(file.language)} · ${file.content.split("\n").length} lines`,
      group: "File",
      run: () => setActiveFile(file.path),
    }));
    const actions: Command[] = [
      {
        id: "action:new",
        label: "Start a new project (opens onboarding)",
        group: "Action",
        run: () => setOnboardingOpen(true),
      },
      {
        id: "action:export",
        label: "Export the project as Markdown",
        group: "Action",
        run: () => downloadProject(files, lastPrompt),
      },
      {
        id: "action:reset",
        label: "Reset the workspace",
        group: "Action",
        run: reset,
      },
      {
        id: "action:rebuild",
        label: "Re-run the last prompt",
        group: "Action",
        run: () => lastPrompt && generate(lastPrompt),
      },
      ...checkpoints.map((checkpoint: Checkpoint) => ({
        id: `cp:${checkpoint.id}`,
        label: `Restore checkpoint: ${checkpoint.label}`,
        group: "History",
        run: () => restore(checkpoint),
      })),
    ];
    return [...actions, ...fileCommands];
  }, [files, checkpoints, lastPrompt, generate, reset, restore, setActiveFile]);

  return (
    <div className="flex h-dvh min-h-dvh flex-col overflow-hidden">
      {/* ── Top bar ── */}
      <header className="flex h-12 shrink-0 items-center gap-3 border-b border-[var(--border)] bg-[var(--surface)]/95 px-3 backdrop-blur">
        <a
          href="/"
          className="flex shrink-0 items-center gap-2 rounded-md pe-1"
          aria-label="Yanzx AI home"
        >
          <Logo size={24} />
          <span className="hidden text-sm font-semibold tracking-tight sm:inline">
            Yanzx<span className="text-[var(--accent)]"> AI</span>
          </span>
        </a>

        <span className="hidden h-4 w-px bg-[var(--border)] sm:block" aria-hidden="true" />

        <p className="min-w-0 truncate text-xs text-[var(--muted)]">
          <span className="text-[var(--foreground)]">{titleFromPrompt(lastPrompt)}</span>
          <span className="ms-2 hidden text-[10px] uppercase tracking-wide sm:inline">
            {files.length} files · {totalLines} lines
          </span>
        </p>

        <div className="ms-auto flex items-center gap-1">
          <button
            type="button"
            onClick={() => setPaletteOpen(true)}
            className="btn-ghost me-1 hidden !py-1.5 !text-[11px] sm:flex"
            aria-label="Search files and commands"
          >
            <Search className="size-3.5" aria-hidden="true" />
            Search
            <kbd className="kbd">⌘K</kbd>
          </button>
          <button
            type="button"
            onClick={() => downloadProject(files, lastPrompt)}
            className="btn-icon"
            aria-label="Export the project as Markdown"
            title="Export as Markdown"
          >
            <Download className="size-4" aria-hidden="true" />
          </button>
          <button
            type="button"
            onClick={reset}
            className="btn-icon"
            aria-label="Reset the workspace"
            title="Reset workspace"
          >
            <RotateCcw className="size-4" aria-hidden="true" />
          </button>
          <button
            type="button"
            onClick={() => setOnboardingOpen(true)}
            className="btn-accent ms-1 hidden !px-3 !py-1.5 !text-xs sm:inline-flex"
          >
            <Sparkles className="size-3.5" aria-hidden="true" />
            New build
          </button>
        </div>
      </header>

      {/* ── Tri-pane body: explorer | canvas | assistant ── */}
      <div className="flex min-h-0 flex-1 flex-col lg:flex-row">
        {explorerOpen && (
          <nav
            aria-label="Project explorer"
            className="pane hidden w-60 shrink-0 flex-col border-e border-[var(--border)] md:flex xl:w-64"
          >
            <div className="flex items-center justify-between border-b border-[var(--border)] px-3 py-2">
              <h2 className="label flex items-center gap-1.5">
                <FileCode2 className="size-3" aria-hidden="true" />
                Explorer
              </h2>
              <button
                type="button"
                onClick={() => setExplorerOpen(false)}
                className="btn-icon !size-6"
                aria-label="Collapse the explorer"
              >
                <PanelLeftClose className="size-3.5" aria-hidden="true" />
              </button>
            </div>

            <div className="min-h-0 flex-1 pt-1.5">
              <FileTree
                files={files}
                activeFile={activeFile}
                onSelect={setActiveFile}
                changedPaths={changedPaths}
              />
            </div>

            <div className="border-t border-[var(--border)] px-3 py-2.5 text-[10px] leading-4 text-[var(--muted)]">
              <p className="flex items-center gap-1.5 font-semibold text-[var(--foreground)]">
                <History className="size-3" aria-hidden="true" />
                {checkpoints.length} checkpoint{checkpoints.length === 1 ? "" : "s"}
              </p>
              <p className="mt-1">
                Workspace saved in this browser. Export any time from the top bar.
              </p>
            </div>
          </nav>
        )}

        {!explorerOpen && (
          <button
            type="button"
            onClick={() => setExplorerOpen(true)}
            className="hidden w-9 shrink-0 cursor-pointer items-start justify-center border-e border-[var(--border)] bg-[var(--surface)] pt-3 text-[var(--muted)] transition-colors hover:text-[var(--foreground)] md:flex"
            aria-label="Expand the explorer"
          >
            <PanelLeftOpen className="size-4" aria-hidden="true" />
          </button>
        )}

        <main className="flex min-h-0 min-w-0 flex-1 flex-col bg-[var(--background)]">
          <Canvas
            files={files}
            activeFile={activeFile}
            isGenerating={isGenerating}
            onSelectFile={setActiveFile}
          />
        </main>

        <div className="flex max-h-[46dvh] min-h-0 shrink-0 flex-col border-t border-[var(--border)] lg:max-h-none lg:border-t-0">
          <AssistantPanel
            messages={messages}
            isGenerating={isGenerating}
            mode={mode}
            notice={notice}
            error={error}
            checkpoints={checkpoints}
            onSend={generate}
            onStop={stop}
            onRestore={restore}
            onClearError={clearError}
            onDownloadAll={() => downloadProject(files, lastPrompt)}
          />
        </div>
      </div>

      <OnboardingModal
        open={onboardingOpen}
        onClose={dismissOnboarding}
        onSubmit={submitFromOnboarding}
        isGenerating={isGenerating}
      />

      <CommandPalette
        open={paletteOpen}
        commands={commands}
        onClose={() => setPaletteOpen(false)}
      />

      <footer className="hidden shrink-0 items-center gap-3 border-t border-[var(--border)] bg-[var(--surface)] px-3 py-1.5 text-[10px] text-[var(--muted)] lg:flex">
        <span className="flex items-center gap-1.5">
          <Keyboard className="size-3" aria-hidden="true" />
          <kbd className="kbd">⌘K</kbd> search
          <kbd className="kbd">⌘/</kbd> new build
          <kbd className="kbd">⌘.</kbd> stop
        </span>
        <span className="ms-auto flex items-center gap-1.5">
          <CommandIcon className="size-3" aria-hidden="true" />
          {mode === "demo" ? "Demo generator" : mode === "live" ? "Model connected" : "Awaiting prompt"}
        </span>
        <span className="flex items-center gap-1">
          Built with <Heart className="size-2.5 text-[var(--danger)]" aria-hidden="true" /> by Yanzx AI
        </span>
      </footer>
    </div>
  );
}
